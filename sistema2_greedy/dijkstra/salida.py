"""Adaptador de salida del bloque Dijkstra: ``ResultadoMapeo`` -> ``PE*.txt``
en el formato del skill 08, y corrida en el simulador (``cgra/src/cgra.py``)."""

import re
from pathlib import Path

from cargador import Cargador
from cgra import CGRA

from .dfg import evaluar

PATRON_PE = re.compile(r"^PE\d+\.txt$")


def escribir_pe(resultado, malla, directorio):
    """Escribe un ``PE{fila}{columna}.txt`` por PE y borra los ``PE*.txt`` que
    no son de esta malla (skill 08). Devuelve la carpeta."""
    if not resultado.valido:
        raise ValueError(f"no se escriben PE*.txt de un mapeo inválido: {resultado.motivo}")
    directorio = Path(directorio)
    directorio.mkdir(parents=True, exist_ok=True)
    ciclos = resultado.metricas["ciclos"]
    ancho = max(2, len(str(max(ciclos - 1, 0))))
    esperados = set()
    for pe in malla.pes:
        nombre = f"{pe.id}.txt"
        esperados.add(nombre)
        lineas = [
            f"// {pe.id} instruction list",
            f"// Mesh position: fila {pe.fila}, columna {pe.columna}",
            f"// PE type: {pe.nombre_tipo} ({pe.letra}) - {', '.join(sorted(pe.instrucciones))}",
            "// Generated by the Dijkstra block (sistema2_greedy/dijkstra), replaces skills 04-07.",
            "// One instruction per execution cycle.",
            "",
        ]
        lineas += [f"{c:0{ancho}d}: {texto}" for c, texto in enumerate(resultado.programa[pe.id])]
        (directorio / nombre).write_text("\n".join(lineas) + "\n", encoding="utf-8")
    for archivo in directorio.iterdir():
        if PATRON_PE.match(archivo.name) and archivo.name not in esperados:
            archivo.unlink()
    return directorio


def ejecutar(formato, ruta_memoria, directorio_pe):
    """Corre los ``PE*.txt`` en el simulador; devuelve ``(inicial, final, ciclos)``,
    con la memoria como ``{región: [valores]}``."""
    cgra = CGRA(formato)
    programa = Cargador(cgra).cargar(ruta_memoria, directorio_pe)
    inicial, _ = cgra.memoria.regiones()
    cgra.ejecutar(programa)
    final, _ = cgra.memoria.regiones()
    return inicial, final, len(programa.ciclos())


def simular(formato, ruta_memoria, directorio_pe, grafo):
    """Corre los ``PE*.txt`` en el simulador y compara la memoria final con
    la del grafo ejecutado en orden de programa.

    Devuelve ``(correcto, diferencias, ciclos)``; ``diferencias`` es una
    lista de ``(región, índice, simulado, esperado)``.
    """
    inicial, final, ciclos = ejecutar(formato, ruta_memoria, directorio_pe)
    esperado = evaluar(grafo, inicial)
    diferencias = [
        (region, i, final[region][i], valor)
        for region, valores in esperado.items()
        for i, valor in enumerate(valores)
        if final[region][i] != valor
    ]
    return not diferencias, diferencias, ciclos
